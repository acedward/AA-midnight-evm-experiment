#!/usr/bin/env bash
# Shared helpers for the Part-0 stack scripts. Sourced, never executed.
#
# PLAN-01 Part 0: one persistent Midnight 2.x network, ports allocated at
# generation time into STACK.env, health asserted from the host.

set -euo pipefail

INFRA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${INFRA_DIR}/.." && pwd)"
STACK_ENV="${INFRA_DIR}/STACK.env"
COMPOSE_FILE="${INFRA_DIR}/docker-compose.yml"
VERSIONS_JSON="${REPO_ROOT}/versions.json"

# --- port allocation -------------------------------------------------------
#
# Base range 10100..63990 (we need P..P+9). Excluded on this machine:
#   10000-10030  live evm-compat stack, populated DB — DO NOT TOUCH
#   9944 / 8088  a local proxy maps these onto that live stack (PART-E Q4)
#   12300-12599  midnight-ref-ai matrix slots (next reserved block 12600-12699)
# 9944/8088 sit below the base range by construction; the two windows below are
# rejected as whole 10-port windows so no allocation can straddle them.
PORT_BASE_MIN=10100
PORT_BASE_MAX=63990
PORT_WINDOW=10

say() { printf '%s\n' "$*" >&2; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# A window [base, base+9] is forbidden if it intersects any reserved range.
window_forbidden() {
  # Two statements, deliberately: `local base=$1 last=$((base + ...))` expands
  # $base BEFORE `local` creates it, so under `set -u` the function only worked
  # when the CALLER happened to have a variable named `base` in scope — which
  # alloc_base_port does. It silently read the caller's value.
  local base=$1
  local last=$((base + PORT_WINDOW - 1))
  local -a ranges=(10000 10030 12300 12599 9944 9944 8088 8088)
  local i lo hi
  for ((i = 0; i < ${#ranges[@]}; i += 2)); do
    lo=${ranges[i]}; hi=${ranges[i + 1]}
    if ((base <= hi && last >= lo)); then return 0; fi
  done
  return 1
}

# Free = nothing LISTENing (lsof) AND we can actually bind it (kernel truth:
# catches TIME_WAIT, other namespaces, and non-lsof-visible holders).
port_free() {
  local p=$1
  if lsof -iTCP:"$p" -sTCP:LISTEN -n -P >/dev/null 2>&1; then return 1; fi
  python3 - "$p" <<'PY'
import socket, sys
port = int(sys.argv[1])
for host in ("127.0.0.1", "0.0.0.0"):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind((host, port))
    except OSError:
        sys.exit(1)
    finally:
        s.close()
sys.exit(0)
PY
}

# Random base whose whole window is free. Re-rolls on any collision.
alloc_base_port() {
  local attempt base p ok
  for attempt in $(seq 1 200); do
    base=$((PORT_BASE_MIN + (RANDOM * 32768 + RANDOM) % (PORT_BASE_MAX - PORT_BASE_MIN + 1)))
    window_forbidden "$base" && continue
    ok=1
    for ((p = base; p < base + PORT_WINDOW; p++)); do
      if ! port_free "$p"; then ok=0; break; fi
    done
    ((ok == 1)) && { printf '%s' "$base"; return 0; }
  done
  die "could not find a free ${PORT_WINDOW}-port window in ${PORT_BASE_MIN}..${PORT_BASE_MAX} after 200 tries"
}

pin() { jq -re --arg k "$1" '.docker[$k]' "$VERSIONS_JSON"; }

# --- STACK.env -------------------------------------------------------------

write_stack_env() {
  local base=$1
  local node=$base indexer_http=$((base + 1)) indexer_ws=$((base + 2)) proof=$((base + 3))
  local secret
  secret="aa$(openssl rand -hex 31)"

  cat >"$STACK_ENV" <<EOF
# GENERATED by infra/stack-up.sh — the single source of truth for this stack.
# Every test and util reads these values; NOTHING may fall back to a default
# port (9944/8088/6300 are a proxy onto another stack on this machine).
# Regenerate by deleting this file and re-running infra/stack-up.sh.
# Generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)

COMPOSE_PROJECT_NAME=midnight-aa-${base}
MIDNIGHT_NETWORK_ID=undeployed

# Base port P=${base}; P+4..P+9 ($((base + 4))..$((base + 9))) reserved for PLAN-05 relayer/dashboard.
AA_BASE_PORT=${base}
AA_NODE_PORT=${node}
AA_INDEXER_HTTP_PORT=${indexer_http}
AA_INDEXER_WS_PORT=${indexer_ws}
AA_PROOF_SERVER_PORT=${proof}

AA_NODE_URL=http://127.0.0.1:${node}
AA_NODE_WS=ws://127.0.0.1:${node}
AA_INDEXER_HTTP=http://127.0.0.1:${indexer_http}/api/v4/graphql
AA_INDEXER_WS=ws://127.0.0.1:${indexer_ws}/api/v4/graphql/ws
AA_PROOF_SERVER=http://127.0.0.1:${proof}

# Image pins mirrored from versions.json (docker.*) at generation time.
AA_NODE_IMAGE=$(pin midnight-node)
AA_INDEXER_IMAGE=$(pin indexer-standalone)
AA_PROOF_SERVER_IMAGE=$(pin proof-server)

AA_INDEXER_SECRET=${secret}
EOF
  say "  wrote ${STACK_ENV} (base port ${base})"
}

load_stack_env() {
  [[ -f "$STACK_ENV" ]] || die "no STACK.env — run infra/stack-up.sh first"
  set -a; . "$STACK_ENV"; set +a
}

compose() { docker compose --env-file "$STACK_ENV" -f "$COMPOSE_FILE" "$@"; }

# Does this stack still exist on the machine (containers or volumes)? A stopped
# stack does — and its chain state is what every DEPLOYMENTS.json address lives
# in, so it must come back on the SAME ports rather than being re-rolled.
stack_exists() {
  local containers volumes
  containers=$(docker ps -aq --filter "label=com.docker.compose.project=${COMPOSE_PROJECT_NAME}" | wc -l)
  volumes=$(docker volume ls -q --filter "label=com.docker.compose.project=${COMPOSE_PROJECT_NAME}" | wc -l)
  ((containers > 0 || volumes > 0))
}

# Has something else taken the ports STACK.env recorded? Only true when the
# stack itself is gone — a running/stopped stack legitimately holds them.
ports_stolen() {
  local p
  for p in "$AA_NODE_PORT" "$AA_INDEXER_HTTP_PORT" "$AA_INDEXER_WS_PORT" "$AA_PROOF_SERVER_PORT"; do
    port_free "$p" || return 0
  done
  return 1
}

# --- host-side health probes ----------------------------------------------
#
# These are the real readiness contract. Container healthchecks are weaker:
# the indexer image has no HTTP client (bash /dev/tcp only) and the proof-server
# image is distroless (no shell at all).

probe_node() {
  local body height
  body=$(curl -sf -m 5 -H 'content-type: application/json' \
    -d '{"id":1,"jsonrpc":"2.0","method":"chain_getHeader","params":[]}' \
    "$AA_NODE_URL" 2>/dev/null) || { echo "unreachable"; return 1; }
  height=$(printf '%s' "$body" | jq -r '.result.number // empty')
  [[ -n "$height" ]] || { echo "no header in response"; return 1; }
  height=$((height))
  ((height > 0)) || { echo "best block ${height}"; return 1; }
  echo "best block ${height}"
}

probe_indexer() {
  local body
  body=$(curl -sf -m 5 -H 'content-type: application/json' \
    -d '{"query":"query { __typename }"}' "$AA_INDEXER_HTTP" 2>/dev/null) \
    || { echo "unreachable"; return 1; }
  if [[ $(printf '%s' "$body" | jq -r '(.errors // []) | length') != 0 ]]; then
    echo "graphql errors: $(printf '%s' "$body" | jq -c '.errors')"; return 1
  fi
  local tn; tn=$(printf '%s' "$body" | jq -r '.data.__typename // empty')
  [[ -n "$tn" ]] || { echo "no __typename"; return 1; }
  echo "GraphQL ${tn}"
}

probe_indexer_ws() {
  # The WS host port maps onto the same container port; assert it is published
  # and accepting connections (a GraphQL-WS handshake needs a real client).
  python3 - "$AA_INDEXER_WS_PORT" <<'PY' || { echo "ws port closed"; return 1; }
import socket, sys
s = socket.create_connection(("127.0.0.1", int(sys.argv[1])), timeout=5)
s.close()
PY
  echo "ws port ${AA_INDEXER_WS_PORT} open"
}

probe_proof_server() {
  curl -sf -m 5 "${AA_PROOF_SERVER}/health" >/dev/null 2>&1 \
    || { echo "unreachable"; return 1; }
  echo "health ok"
}

# wait_ready <name> <probe-fn> <timeout-seconds>
wait_ready() {
  local name=$1 fn=$2 timeout=$3
  local deadline=$((SECONDS + timeout)) detail
  while ((SECONDS < deadline)); do
    if detail=$("$fn" 2>/dev/null); then
      say "  ✓ ${name} ready (${detail})"
      return 0
    fi
    sleep 2
  done
  say "  ✗ ${name} not ready after ${timeout}s (last: ${detail:-no probe result})"
  return 1
}

# All three services green? Quiet — used for the reuse decision.
stack_healthy() {
  probe_node >/dev/null 2>&1 && probe_indexer >/dev/null 2>&1 &&
    probe_indexer_ws >/dev/null 2>&1 && probe_proof_server >/dev/null 2>&1
}
